/**
 * The session model: plain data plus one pure function, `apply`.
 *
 * State changes only by applying operations. `apply` never throws on a stale or
 * conflicting operation; it reports that the operation did not apply. That is
 * what lets two machines run the same operations in the same order and end in
 * the same state, whatever each of them was looking at when it issued them.
 */

export type Id = string;

/** Identifies one operation. Unique across the whole session. */
export type OpId = string;

/** For each editable field of a track, the operation that last wrote it. */
export interface TrackRev {
  readonly name: OpId;
}

/** For each editable field of a clip, the operation that last wrote it. */
export interface ClipRev {
  readonly trackId: OpId;
  readonly start: OpId;
  readonly length: OpId;
}

export type ClipField = keyof ClipRev;
const CLIP_FIELDS: readonly ClipField[] = ['trackId', 'start', 'length'];

export interface NewTrack {
  readonly id: Id;
  readonly name: string;
}

export interface Track extends NewTrack {
  readonly rev: TrackRev;
}

export interface NewClip {
  readonly id: Id;
  readonly trackId: Id;
  /** Position on the timeline, in ticks. A non-negative integer. */
  readonly start: number;
  /** Duration in ticks. A positive integer. */
  readonly length: number;
  /** Content identity of the audio this clip plays. Never a file path. */
  readonly sampleHash: string;
}

export interface Clip extends NewClip {
  readonly rev: ClipRev;
}

export interface SessionState {
  readonly trackOrder: readonly Id[];
  readonly tracks: Readonly<Record<Id, Track>>;
  readonly clips: Readonly<Record<Id, Clip>>;
}

export const emptyState: SessionState = Object.freeze({
  trackOrder: Object.freeze([]),
  tracks: Object.freeze({}),
  clips: Object.freeze({}),
});

export interface ClipPatch {
  readonly trackId?: Id;
  readonly start?: number;
  readonly length?: number;
}

/**
 * Operations.
 *
 * Edits a user makes directly (`clip.move`, `clip.resize`, `track.rename`, a plain
 * add or remove) are unconditional: the later edit in relay order wins.
 *
 * Undo and redo are different. They are generated by `apply` as the inverse of an
 * edit, and they are guarded by revisions: they apply only while every field they
 * would write was last written by the operation they are reversing. When they
 * apply they also put the previous revisions back, so undoing one edit re-arms
 * the undo of the edit before it. A guarded operation therefore never overwrites
 * something another person changed in the meantime, even if that person happened
 * to set the same value.
 */
export type Op =
  | {
      readonly type: 'track.add';
      readonly track: NewTrack;
      readonly index: number;
      /** Present when this restores a removed track: its revision and the clips it held. */
      readonly restore?: { readonly rev: TrackRev; readonly clips: readonly Clip[] };
    }
  | {
      readonly type: 'track.remove';
      readonly id: Id;
      /** Present on undo and redo: the track and its clips must be exactly this. */
      readonly ifUnchanged?: { readonly rev: TrackRev; readonly clips: readonly Clip[] };
    }
  | {
      readonly type: 'track.rename';
      readonly id: Id;
      readonly name: string;
      readonly undo?: { readonly expect: OpId; readonly restore: OpId };
    }
  | {
      readonly type: 'clip.add';
      readonly clip: NewClip;
      /** Present when this restores a removed clip. */
      readonly rev?: ClipRev;
    }
  | { readonly type: 'clip.move'; readonly id: Id; readonly trackId: Id; readonly start: number }
  | { readonly type: 'clip.resize'; readonly id: Id; readonly start: number; readonly length: number }
  | {
      /** The guarded form of move and resize. Only ever produced as an inverse. */
      readonly type: 'clip.patch';
      readonly id: Id;
      readonly set: ClipPatch;
      readonly expect: Partial<ClipRev>;
      readonly restore: Partial<ClipRev>;
    }
  | {
      readonly type: 'clip.remove';
      readonly id: Id;
      /** Present on undo and redo: the clip must be exactly this. */
      readonly ifClip?: Clip;
    };

export type RejectReason =
  | 'invalid' // malformed values, such as a negative start
  | 'id-exists' // adding something whose id is already taken
  | 'target-missing' // the track or clip is gone
  | 'track-missing' // the destination track is gone
  | 'guard-failed' // someone else has written the target since
  | 'no-change'; // the operation would leave the state as it is

export type ApplyResult =
  | { readonly applied: true; readonly state: SessionState; readonly inverse: Op }
  | { readonly applied: false; readonly state: SessionState; readonly reason: RejectReason };

const has = (record: object, key: string): boolean => Object.hasOwn(record, key);
const isTick = (n: number): boolean => Number.isInteger(n) && n >= 0;
const isLength = (n: number): boolean => Number.isInteger(n) && n > 0;
const byId = (a: { id: Id }, b: { id: Id }): number => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0);

export const sameClip = (a: Clip, b: Clip): boolean =>
  a.id === b.id &&
  a.sampleHash === b.sampleHash &&
  CLIP_FIELDS.every((field) => a[field] === b[field] && a.rev[field] === b.rev[field]);

const sameClips = (a: readonly Clip[], b: readonly Clip[]): boolean => {
  if (a.length !== b.length) return false;
  const sortedB = [...b].sort(byId);
  return [...a].sort(byId).every((clip, i) => {
    const other = sortedB[i];
    return other !== undefined && sameClip(clip, other);
  });
};

const hasValidSpan = (clip: { start: number; length: number }): boolean => isTick(clip.start) && isLength(clip.length);

/** Clips on one track, sorted by id so the result is the same on every machine. */
export function clipsOnTrack(state: SessionState, trackId: Id): Clip[] {
  return Object.values(state.clips)
    .filter((clip) => clip.trackId === trackId)
    .sort(byId);
}

function without<T>(record: Readonly<Record<Id, T>>, ids: readonly Id[]): Record<Id, T> {
  const next: Record<Id, T> = { ...record };
  for (const id of ids) delete next[id];
  return next;
}

const ok = (state: SessionState, inverse: Op): ApplyResult => ({ applied: true, state, inverse });
const no = (state: SessionState, reason: RejectReason): ApplyResult => ({ applied: false, state, reason });

type ClipValues = Pick<NewClip, ClipField>;

/**
 * Write new values to some fields of a clip.
 *
 * `fields` are the fields being written. `revFor` gives the revision each one
 * gets. The inverse writes the old values back to the same fields, guarded on the
 * revisions this write leaves behind, and restores the revisions that were there.
 */
function writeClip(
  state: SessionState,
  clip: Clip,
  fields: readonly ClipField[],
  values: ClipValues,
  revFor: (field: ClipField) => OpId,
): ApplyResult {
  const set: { -readonly [K in ClipField]?: ClipValues[K] } = {};
  const expect: { -readonly [K in ClipField]?: OpId } = {};
  const restore: { -readonly [K in ClipField]?: OpId } = {};
  const rev: { -readonly [K in ClipField]: OpId } = { ...clip.rev };
  for (const field of fields) {
    rev[field] = revFor(field);
    expect[field] = rev[field];
    restore[field] = clip.rev[field];
  }
  if (fields.includes('trackId')) set.trackId = clip.trackId;
  if (fields.includes('start')) set.start = clip.start;
  if (fields.includes('length')) set.length = clip.length;
  const next: Clip = { ...clip, ...values, rev };
  return ok(
    { ...state, clips: { ...state.clips, [clip.id]: next } },
    { type: 'clip.patch', id: clip.id, set, expect, restore },
  );
}

/** A direct edit: write only the fields whose value actually changes, stamped with this operation. */
function editClip(state: SessionState, clip: Clip, target: ClipValues, opId: OpId): ApplyResult {
  const changed = CLIP_FIELDS.filter((field) => clip[field] !== target[field]);
  if (changed.length === 0) return no(state, 'no-change');
  return writeClip(state, clip, changed, target, () => opId);
}

/**
 * Apply one operation. Pure and deterministic: the same state, operation and id
 * always give the same result. The input state is never mutated.
 *
 * When the operation applies, `inverse` is the guarded operation that undoes it.
 */
export function apply(state: SessionState, op: Op, opId: OpId): ApplyResult {
  switch (op.type) {
    case 'track.add': {
      const { id, name } = op.track;
      if (!isTick(op.index)) return no(state, 'invalid');
      if (has(state.tracks, id)) return no(state, 'id-exists');
      const at = Math.min(op.index, state.trackOrder.length);
      const track: Track = { id, name, rev: op.restore?.rev ?? { name: opId } };
      const restored = (op.restore?.clips ?? [])
        .filter((clip) => clip.trackId === id && hasValidSpan(clip) && !has(state.clips, clip.id))
        .sort(byId);
      const clips: Record<Id, Clip> = { ...state.clips };
      for (const clip of restored) clips[clip.id] = clip;
      return ok(
        {
          trackOrder: [...state.trackOrder.slice(0, at), id, ...state.trackOrder.slice(at)],
          tracks: { ...state.tracks, [id]: track },
          clips,
        },
        { type: 'track.remove', id, ifUnchanged: { rev: track.rev, clips: restored } },
      );
    }

    case 'track.remove': {
      const track = state.tracks[op.id];
      if (track === undefined || !has(state.tracks, op.id)) return no(state, 'target-missing');
      const onTrack = clipsOnTrack(state, op.id);
      if (op.ifUnchanged && !(track.rev.name === op.ifUnchanged.rev.name && sameClips(onTrack, op.ifUnchanged.clips))) {
        return no(state, 'guard-failed');
      }
      return ok(
        {
          trackOrder: state.trackOrder.filter((id) => id !== op.id),
          tracks: without(state.tracks, [op.id]),
          clips: without(
            state.clips,
            onTrack.map((clip) => clip.id),
          ),
        },
        {
          type: 'track.add',
          track: { id: track.id, name: track.name },
          index: state.trackOrder.indexOf(op.id),
          restore: { rev: track.rev, clips: onTrack },
        },
      );
    }

    case 'track.rename': {
      const track = state.tracks[op.id];
      if (track === undefined || !has(state.tracks, op.id)) return no(state, 'target-missing');
      if (op.undo && track.rev.name !== op.undo.expect) return no(state, 'guard-failed');
      if (!op.undo && track.name === op.name) return no(state, 'no-change');
      const rev: TrackRev = { name: op.undo ? op.undo.restore : opId };
      return ok(
        { ...state, tracks: { ...state.tracks, [op.id]: { ...track, name: op.name, rev } } },
        { type: 'track.rename', id: op.id, name: track.name, undo: { expect: rev.name, restore: track.rev.name } },
      );
    }

    case 'clip.add': {
      if (!hasValidSpan(op.clip)) return no(state, 'invalid');
      if (has(state.clips, op.clip.id)) return no(state, 'id-exists');
      if (!has(state.tracks, op.clip.trackId)) return no(state, 'track-missing');
      const clip: Clip = { ...op.clip, rev: op.rev ?? { trackId: opId, start: opId, length: opId } };
      return ok(
        { ...state, clips: { ...state.clips, [clip.id]: clip } },
        { type: 'clip.remove', id: clip.id, ifClip: clip },
      );
    }

    case 'clip.move': {
      const clip = state.clips[op.id];
      if (!isTick(op.start)) return no(state, 'invalid');
      if (clip === undefined || !has(state.clips, op.id)) return no(state, 'target-missing');
      if (!has(state.tracks, op.trackId)) return no(state, 'track-missing');
      return editClip(state, clip, { trackId: op.trackId, start: op.start, length: clip.length }, opId);
    }

    case 'clip.resize': {
      const clip = state.clips[op.id];
      if (!hasValidSpan(op)) return no(state, 'invalid');
      if (clip === undefined || !has(state.clips, op.id)) return no(state, 'target-missing');
      return editClip(state, clip, { trackId: clip.trackId, start: op.start, length: op.length }, opId);
    }

    case 'clip.patch': {
      const fields = CLIP_FIELDS.filter((field) => op.set[field] !== undefined);
      const complete = fields.every((field) => op.expect[field] !== undefined && op.restore[field] !== undefined);
      if (fields.length === 0 || !complete) return no(state, 'invalid');
      const clip = state.clips[op.id];
      if (clip === undefined || !has(state.clips, op.id)) return no(state, 'target-missing');
      const target: ClipValues = {
        trackId: op.set.trackId ?? clip.trackId,
        start: op.set.start ?? clip.start,
        length: op.set.length ?? clip.length,
      };
      if (!hasValidSpan(target)) return no(state, 'invalid');
      if (!fields.every((field) => clip.rev[field] === op.expect[field])) return no(state, 'guard-failed');
      if (!has(state.tracks, target.trackId)) return no(state, 'track-missing');
      return writeClip(state, clip, fields, target, (field) => op.restore[field] ?? opId);
    }

    case 'clip.remove': {
      const clip = state.clips[op.id];
      if (clip === undefined || !has(state.clips, op.id)) return no(state, 'target-missing');
      if (op.ifClip && !sameClip(clip, op.ifClip)) return no(state, 'guard-failed');
      const { rev, ...values } = clip;
      return ok({ ...state, clips: without(state.clips, [op.id]) }, { type: 'clip.add', clip: values, rev });
    }
  }
}

/**
 * A stable text form of the state, revisions included. Two states are equal
 * exactly when their canonical forms are equal, regardless of insertion order.
 */
export function canonical(state: SessionState): string {
  return JSON.stringify({
    trackOrder: state.trackOrder,
    tracks: Object.values(state.tracks)
      .sort(byId)
      .map((track) => [track.id, track.name, track.rev.name]),
    clips: Object.values(state.clips)
      .sort(byId)
      .map((clip) => [
        clip.id,
        clip.trackId,
        clip.start,
        clip.length,
        clip.sampleHash,
        clip.rev.trackId,
        clip.rev.start,
        clip.rev.length,
      ]),
  });
}

/** Structural rules every reachable state must satisfy. Returns the violations. */
export function checkInvariants(state: SessionState): string[] {
  const problems: string[] = [];
  const trackIds = Object.keys(state.tracks);
  if (new Set(state.trackOrder).size !== state.trackOrder.length) problems.push('trackOrder has duplicates');
  if (state.trackOrder.length !== trackIds.length || !state.trackOrder.every((id) => has(state.tracks, id))) {
    problems.push('trackOrder and tracks disagree');
  }
  for (const [id, track] of Object.entries(state.tracks)) {
    if (track.id !== id) problems.push(`track ${id} is stored under the wrong key`);
  }
  for (const [id, clip] of Object.entries(state.clips)) {
    if (clip.id !== id) problems.push(`clip ${id} is stored under the wrong key`);
    if (!has(state.tracks, clip.trackId)) problems.push(`clip ${id} is on missing track ${clip.trackId}`);
    if (!hasValidSpan(clip)) problems.push(`clip ${id} has an invalid span`);
  }
  return problems;
}
